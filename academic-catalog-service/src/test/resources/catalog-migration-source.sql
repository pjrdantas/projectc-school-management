CREATE TABLE nivel_ensino (
    id_nivel_ensino uuid PRIMARY KEY, codigo varchar(40) NOT NULL UNIQUE, descricao varchar(120) NOT NULL);
CREATE TABLE turno (
    id_turno uuid PRIMARY KEY, codigo varchar(40) NOT NULL UNIQUE, descricao varchar(120) NOT NULL);
CREATE TABLE periodo_letivo (
    id_periodo_letivo uuid PRIMARY KEY, id_escola uuid NOT NULL, nome varchar(80) NOT NULL,
    ano integer NOT NULL, data_inicio date NOT NULL, data_fim date NOT NULL,
    ativo boolean NOT NULL, created_at timestamp NOT NULL);
CREATE TABLE serie (
    id_serie uuid PRIMARY KEY, id_escola uuid NOT NULL, nome varchar(80) NOT NULL,
    ordem integer NOT NULL, id_nivel_ensino uuid, created_at timestamp NOT NULL);
CREATE TABLE disciplina (
    id_disciplina uuid PRIMARY KEY, id_escola uuid NOT NULL, nome varchar(120) NOT NULL,
    carga_horaria integer, ativo boolean NOT NULL, created_at timestamp NOT NULL);
CREATE TABLE turma (
    id_turma uuid PRIMARY KEY, id_escola uuid NOT NULL, codigo varchar(20) NOT NULL,
    nome varchar(120) NOT NULL, capacidade integer NOT NULL, id_periodo_letivo uuid NOT NULL,
    id_serie uuid NOT NULL, id_turno uuid, ativo boolean NOT NULL, created_at timestamp NOT NULL);
CREATE TABLE turma_disciplina (
    id_turma_disciplina uuid PRIMARY KEY, id_turma uuid NOT NULL, id_disciplina uuid NOT NULL,
    carga_horaria integer, created_at timestamp NOT NULL);

