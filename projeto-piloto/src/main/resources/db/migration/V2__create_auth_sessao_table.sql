-- TABELA AUTH_SESSAO: Rastreamento de sessões ativas por usuário
CREATE TABLE IF NOT EXISTS AUTH_SESSAO (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    AUTH_USUARIO_ID BIGINT NOT NULL,
    DS_TOKEN VARCHAR(1000) NOT NULL,
    DS_REFRESH_TOKEN VARCHAR(1000) NOT NULL,
    DATA_CRIACAO TIMESTAMP NOT NULL,
    DATA_EXPIRACAO TIMESTAMP NOT NULL,
    FL_ATIVO VARCHAR(1) DEFAULT 'S' NOT NULL,
    CONSTRAINT PK_AUTH_SESSAO PRIMARY KEY (id),
    CONSTRAINT FK_SESSAO_USUARIO FOREIGN KEY (AUTH_USUARIO_ID) REFERENCES AUTH_USUARIO(ID),
    CONSTRAINT UK_TOKEN_USUARIO UNIQUE (AUTH_USUARIO_ID, DS_TOKEN)
);

-- Índices para melhorar performance nas buscas
CREATE INDEX IF NOT EXISTS IDX_SESSAO_USUARIO ON AUTH_SESSAO(AUTH_USUARIO_ID);
CREATE INDEX IF NOT EXISTS IDX_SESSAO_ATIVA ON AUTH_SESSAO(FL_ATIVO);
CREATE INDEX IF NOT EXISTS IDX_SESSAO_TOKEN ON AUTH_SESSAO(DS_TOKEN);
